-- Migration to create providers and public_expenses tables
-- Providers table stores vendor information for invoices with VAT
CREATE TABLE IF NOT EXISTS providers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    cif TEXT,
    address TEXT,
    email TEXT,
    phone TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Optional unique index on provider name
CREATE UNIQUE INDEX IF NOT EXISTS idx_providers_name ON providers(name);

-- Public expenses table stores expenses from government entities (no VAT)
CREATE TABLE IF NOT EXISTS public_expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer_name TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    description TEXT,
    expense_date DATE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Index on expense date for reporting
CREATE INDEX IF NOT EXISTS idx_public_expenses_date ON public_expenses(expense_date);
