-- 1. TABLA: gestarian_clients (Cartera de Clientes del Taller)
CREATE TABLE IF NOT EXISTS public.gestarian_clients (
    id TEXT PRIMARY KEY,
    client_number BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    name TEXT NOT NULL,
    cif TEXT NOT NULL,
    address TEXT,
    phone TEXT,
    email TEXT,
    plates TEXT[] DEFAULT '{}',
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_gestarian_clients_client_number ON public.gestarian_clients(client_number);
CREATE INDEX IF NOT EXISTS idx_gestarian_clients_cif ON public.gestarian_clients(cif);
CREATE INDEX IF NOT EXISTS idx_gestarian_clients_name ON public.gestarian_clients(name);

-- 2. TABLA: gestarian_short_links (Enlaces Cortos de Documentos y Expedientes)
CREATE TABLE IF NOT EXISTS public.gestarian_short_links (
    id TEXT PRIMARY KEY,
    target_url TEXT NOT NULL,
    doc_number TEXT,
    expediente TEXT,
    payload JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABLA: providers (Proveedores detectados automáticamente por escaneo de facturas)
CREATE TABLE IF NOT EXISTS public.providers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    cif TEXT,
    address TEXT,
    email TEXT,
    phone TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_providers_name ON public.providers(name);

-- 4. TABLA: public_expenses (Gastos de Organismos Públicos: Tasas, IBI, Vados, Multas - Sin IVA)
CREATE TABLE IF NOT EXISTS public.public_expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payer_name TEXT NOT NULL,
    amount NUMERIC NOT NULL,
    description TEXT,
    expense_date DATE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_public_expenses_date ON public.public_expenses(expense_date);

-- ------------------------------------------------------------------------------
-- 5. POLÍTICAS DE SEGURIDAD (Row Level Security - RLS)
-- Permite lectura y escritura con la clave anónima y de servicio de Gestarian
-- ------------------------------------------------------------------------------
ALTER TABLE public.gestarian_clients ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.gestarian_short_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.providers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.public_expenses ENABLE ROW LEVEL SECURITY;

-- Políticas de acceso para gestarian_clients
CREATE POLICY "Allow all on gestarian_clients" ON public.gestarian_clients
    FOR ALL USING (true) WITH CHECK (true);

-- Políticas de acceso para gestarian_short_links
CREATE POLICY "Allow all on gestarian_short_links" ON public.gestarian_short_links
    FOR ALL USING (true) WITH CHECK (true);

-- Políticas de acceso para providers
CREATE POLICY "Allow all on providers" ON public.providers
    FOR ALL USING (true) WITH CHECK (true);

-- Políticas de acceso para public_expenses
CREATE POLICY "Allow all on public_expenses" ON public.public_expenses
    FOR ALL USING (true) WITH CHECK (true);
